export function getDatingPriorityItems(perspectiveKey) {
  const perspective = DATING_PRIORITY_PERSPECTIVES[perspectiveKey]
  if (!perspective) return []

  return perspective.categories.flatMap((category) =>
    category.items.map(([label, description], index) => ({
      id: `${perspectiveKey}:${category.key}:${index}`,
      categoryKey: category.key,
      categoryLabel: category.label,
      categoryIcon: category.icon,
      label,
      description: description || '',
    })),
  )
}

export function getDatingVetoItems(perspectiveKey) {
  const perspective = DATING_PRIORITY_PERSPECTIVES[perspectiveKey]
  if (!perspective) return []

  return perspective.vetoConditions.map(([label, strength], index) => ({
    id: `${perspectiveKey}:veto:${index}`,
    rank: index + 1,
    label,
    strength,
  }))
}
